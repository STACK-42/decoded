export type ResolvedIcon = {
  simpleIcon?: SimpleIcon;
  lucideIcon?: ComponentType<{ className?: string }>;
  color?: string;
};

type Rule = ResolvedIcon & { match: RegExp };

const escape = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

/** Whole-word, case-insensitive match on any of the phrases (a trailing "s" or "es" is allowed),
    so "ram" doesn't fire on "programming" and "rsa" doesn't fire on "traversals". */
const words = (...phrases: string[]) =>
  new RegExp(`(?<![\\w])(?:${phrases.map((p) => escape(p) + (/[a-z]$/i.test(p) ? "(?:e?s)?" : "")).join("|")})(?![\\w])`, "i");

const brand = (icon: SimpleIcon, color: string, ...phrases: string[]): Rule => ({
  simpleIcon: icon,
  color,
  match: words(...phrases),
});
const topic = (icon: ResolvedIcon["lucideIcon"], color: string, ...phrases: string[]): Rule => ({
  lucideIcon: icon,
  color,
  match: words(...phrases),
});

