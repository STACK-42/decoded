/** Shown when nothing matches, so every application card still carries an icon. */
export const FALLBACK_ICON: ResolvedIcon = { lucideIcon: Wrench, color: "#94A3B8" };

const firstMatch = (rules: Rule[], text: string): ResolvedIcon | null => {
  if (!text) return null;
  const rule = rules.find((r) => r.match.test(text));
  return rule ? { simpleIcon: rule.simpleIcon, lucideIcon: rule.lucideIcon, color: rule.color } : null;
};

/**
 * Picks the icon for an application card. The `tool` tag is the stronger signal, so it is tried
 * first: brands, then topics. Only then is the title read, the same way. Returns `null` when
 * nothing fits; callers that always want an icon use `FALLBACK_ICON`.
 */
export function resolveToolIcon(tool?: string, title?: string): ResolvedIcon | null {
  for (const text of [tool ?? "", title ?? ""]) {
    const hit = firstMatch(BRANDS, text) ?? firstMatch(TOPICS, text);
    if (hit) return hit;
  }
  return null;
}
